#!/usr/bin/env bash
# Discovers the IP address each external dependency (the five PostgreSQL
# containers, RabbitMQ and MinIO from infra/docker/docker-compose.yml) holds
# on the shared `bank-usac-local` Docker network, and writes a Helm values
# override with them — the `external.<dep>.dockerNetwork.host` values the
# chart's selectorless Endpoints need in `external.mode: dockerNetwork`
# (ADR-007, docs/architecture/adr/ADR-007-local-orchestration.md).
#
# Run this after the Compose stack is up (`pnpm dev:infra` or
# `pnpm images:up`) and after the kind cluster has joined `bank-usac-local`
# (see ../cluster.yaml), and again before every `helm upgrade --install`:
# Docker reassigns these addresses whenever a container is recreated, so a
# stale value here is a silent outage — the pod stays `Running`, never
# `Ready` — not a rendering error.
set -euo pipefail

NETWORK="bank-usac-local"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${SCRIPT_DIR}/../generated-external.values.yaml"

# container name -> the values.yaml key under `external:`, as two parallel
# arrays indexed together. Not an associative array on purpose: macOS ships
# bash 3.2, which has no `declare -A`, and this must run on the team's Macs.
CONTAINERS=(
  postgres-customer
  postgres-account
  postgres-transaction
  postgres-payment
  postgres-notification-audit
  rabbitmq
  minio
)
KEYS=(
  postgresCustomer
  postgresAccount
  postgresTransaction
  postgresPayment
  postgresNotificationAudit
  rabbitmq
  minio
)

{
  echo "# Generated by discover-external-ips.sh — do not edit by hand, do not commit."
  echo "# Regenerate before every install; these IPs are only stable while the"
  echo "# containers behind them are not recreated."
  echo "external:"
} > "${OUT}"

for i in "${!CONTAINERS[@]}"; do
  container="${CONTAINERS[$i]}"
  if ! docker inspect "${container}" >/dev/null 2>&1; then
    echo "error: container '${container}' is not running — start the infra" \
      "stack first ('pnpm dev:infra' or 'pnpm images:up')" >&2
    exit 1
  fi

  ip="$(docker inspect "${container}" \
    --format "{{with index .NetworkSettings.Networks \"${NETWORK}\"}}{{.IPAddress}}{{end}}")"

  if [[ -z "${ip}" ]]; then
    echo "error: container '${container}' is not attached to the" \
      "'${NETWORK}' network — it is declared by infra/docker/docker-compose.yml," \
      "which must be the stack that started it" >&2
    exit 1
  fi

  key="${KEYS[$i]}"
  {
    echo "  ${key}:"
    echo "    dockerNetwork:"
    echo "      host: \"${ip}\""
  } >> "${OUT}"
done

echo "wrote ${OUT}" >&2
echo "" >&2
echo "install with, e.g.:" >&2
echo "  helm upgrade --install bank-usac infra/k8s/helm/bank-usac \\" >&2
echo "    --namespace bank-usac --create-namespace \\" >&2
echo "    -f ${OUT} \\" >&2
echo "    --set secrets.jwtSecret=... \\" >&2
echo "    # ...and every other value templates/secret.yaml marks required." >&2
