import { BadRequestException, ValidationPipe } from '@nestjs/common';
import type { PipeTransform, Type } from '@nestjs/common';
import type { ValidationError } from 'class-validator';

/** What every route reports back once a body or query fails to validate. */
interface ValidationFailureBody {
  readonly message: string;
  readonly field: string;
}

const FALLBACK_MESSAGE = 'El valor enviado no es válido.';

/**
 * A property that survived `whitelist` only to be refused by
 * `forbidNonWhitelisted` — an undeclared field riding along in the request.
 *
 * class-validator's own text for this ("property X should not exist") is
 * generated by the pipe rather than a decorator, so there is no `message:` to
 * override at the call site. This is the one place that can catch it.
 */
function isUnexpectedProperty(error: ValidationError): boolean {
  return error.constraints !== undefined && 'whitelistValidation' in error.constraints;
}

/**
 * The first constraint a rejected value actually failed, as a field path and
 * a message meant for a person — never the raw English class-validator
 * produces when a decorator carries no `message:` of its own.
 *
 * Walks into `children` so a nested DTO (`amount` inside `TransferDto`) reports
 * `amount.amountMinor` rather than stopping at the object that contains it.
 */
function firstFailureOf(errors: readonly ValidationError[], prefix = ''): ValidationFailureBody {
  for (const error of errors) {
    const field = prefix === '' ? error.property : `${prefix}.${error.property}`;

    if (isUnexpectedProperty(error)) {
      return { field, message: 'La solicitud incluye un campo que no reconocemos.' };
    }

    if (error.constraints !== undefined) {
      const [message] = Object.values(error.constraints);
      return { field, message: message ?? FALLBACK_MESSAGE };
    }

    if (error.children !== undefined && error.children.length > 0) {
      return firstFailureOf(error.children, field);
    }
  }

  return { field: prefix, message: FALLBACK_MESSAGE };
}

/**
 * Turns class-validator's raw complaints into the shape
 * `GatewayExceptionFilter` reads `message` and `field` off of.
 *
 * Left to its defaults, Nest reports every failure as an array of English
 * sentences, and the filter used to guess the offending field by splitting
 * the first one on a space — which broke the moment a message stopped
 * starting with the property name, and reported the wrong field outright for
 * `forbidNonWhitelisted`, whose sentence starts with the word "property".
 *
 * Exported rather than kept local to `validated()` because the app also
 * registers a global `ValidationPipe` (`APP_PIPE` in `app.module.ts`) as a
 * safety net for any parameter that reaches a controller without going
 * through `validated()`. Global pipes run before a route's own, so whichever
 * one actually rejects the request must produce the same shape — a caller
 * cannot tell which of the two pipes caught their mistake, and should not be
 * able to.
 */
export function validationExceptionFactory(errors: ValidationError[]): BadRequestException {
  return new BadRequestException(firstFailureOf(errors));
}

/**
 * Validates a body against a DTO, naming the class explicitly.
 *
 * The global pipe would normally infer the class from `design:paramtypes`,
 * which TypeScript only emits when the DTO is imported as a **value**. Lint
 * rules that rewrite unused-as-value imports to `import type` therefore break
 * validation — and break it silently, because the pipe then sees `Object`,
 * finds no constraints, and lets everything through.
 *
 * Naming the type here removes that trap entirely: the DTO is used as a value,
 * so no rewrite is possible, and the route says out loud what it validates.
 */
export function validated(dto: Type<unknown>): PipeTransform {
  return new ValidationPipe({
    expectedType: dto,
    whitelist: true,
    forbidNonWhitelisted: true,
    transform: true,
    exceptionFactory: validationExceptionFactory,
  });
}
